package androidx.compose.ui.webcanvas.text.unicode

import kotlin.test.Test
import kotlin.test.fail

/**
 * Runs the test cases of the official Unicode conformance test files of the algorithms implemented
 * here (line breaking and bidi; the browser segments graphemes and words), embedded in
 * UnicodeConformanceTestData.kt (generated by scripts/generate_unicode_tables.py; LineBreakTest.txt
 * and BidiCharacterTest.txt are subsets, regenerate with --full-test-data to run all of them
 * locally).
 */
class UnicodeConformanceTest {

    @Test
    fun lineBreakTest() {
        val cases = readBreakTestCases(LINE_BREAK_TEST_DATA)
        val failures = mutableListOf<String>()
        for (case in cases) {
            val breaks = lineBreaks(case.text)
            val actual = IntArray(breaks.size) { lineBreakPosition(breaks[it]) }
            // The test files mark sot as a non-break and eot as a break.
            val expected = case.expectedBoundaries()
            if (!actual.contentEquals(expected)) failures += case.describe("lineBreaks", actual)
        }
        assertAllPassed("LineBreakTest", cases.size, failures)
    }

    @Test
    fun bidiCharacterTest() {
        val reader = ConformanceDataReader(BIDI_CHARACTER_TEST_DATA)
        val failures = mutableListOf<String>()
        repeat(reader.testCount) {
            val codePoints = IntArray(reader.number()) { reader.codePoint() }
            val direction = reader.number()
            val expectedParagraphLevel = reader.number()
            // -1 for characters removed by rule X9.
            val expectedLevels = IntArray(codePoints.size) { reader.number() - 1 }
            val expectedOrder = IntArray(reader.number()) { reader.number() }

            val text = codePointsToString(codePoints)
            // Compose resolves the direction of a paragraph itself: the paragraph level the test
            // case expects (from the direction it gives, or from its text) is given.
            val paragraph = BidiText(text, expectedParagraphLevel)
            // All test characters are in the BMP, so code units and code points coincide.
            val levels = paragraph.lineLevels(0, text.length)
            val order = paragraph.visualOrder(0, text.length).filter { expectedLevels[it] >= 0 }
            val levelsMatch =
                expectedLevels.indices.all {
                    expectedLevels[it] < 0 || expectedLevels[it] == levels[it].toInt()
                }
            if (!levelsMatch || order != expectedOrder.toList()) {
                failures +=
                    "${codePoints.toHex()}; $direction, level $expectedParagraphLevel: expected " +
                        "levels ${expectedLevels.joinToString(" ")}, order " +
                        "${expectedOrder.joinToString(" ")}; got levels ${levels.joinToString(" ")}" +
                        ", order ${order.joinToString(" ")}"
            }
        }
        check(reader.isExhausted()) { "Unexpected trailing test data" }
        assertAllPassed("BidiCharacterTest", reader.testCount, failures)
    }

    private fun assertAllPassed(name: String, total: Int, failures: List<String>) {
        println("$name: ${total - failures.size} / $total test cases passed")
        if (failures.isNotEmpty()) {
            fail(
                "$name: ${failures.size} of $total test cases failed:\n" +
                    failures.take(20).joinToString("\n")
            )
        }
    }
}

/** A test case of LineBreakTest.txt. */
internal class BreakTestCase(
    val codePoints: IntArray,
    /** Whether there is a break before code point `i` (index `codePoints.size` is eot). */
    val breaks: BooleanArray,
) {
    val text: String = codePointsToString(codePoints)

    /** The code unit offsets of the expected breaks. */
    fun expectedBoundaries(): IntArray {
        val result = mutableListOf<Int>()
        var offset = 0
        for (i in 0..codePoints.size) {
            if (breaks[i]) result += offset
            if (i < codePoints.size) offset += charCount(codePoints[i])
        }
        return result.toIntArray()
    }

    fun describe(what: String, actual: IntArray): String =
        "${codePoints.toHex()}: $what expected ${expectedBoundaries().joinToString()}, " +
            "got ${actual.joinToString()}"
}

/** Decodes the test data of UnicodeConformanceTestData.kt. */
internal class ConformanceDataReader(data: String) {
    private val reader = EncodedDataReader(data)
    private val alphabet: IntArray
    val testCount: Int

    init {
        var codePoint = 0
        alphabet =
            IntArray(reader.next()) {
                codePoint += reader.nextSigned()
                codePoint
            }
        testCount = reader.next()
    }

    fun number(): Int = reader.next()

    fun codePoint(): Int = alphabet[reader.next()]

    /** Reads [count] flags stored in chunks of 15 bits. */
    fun flags(count: Int): BooleanArray {
        val result = BooleanArray(count)
        var i = 0
        while (i < count) {
            val chunk = reader.next()
            for (bit in 0 until minOf(15, count - i)) result[i + bit] = chunk and (1 shl bit) != 0
            i += 15
        }
        return result
    }

    fun isExhausted(): Boolean = !reader.hasNext()
}

/** Reads the next zigzag-encoded signed integer: the test data stores code point deltas so. */
private fun EncodedDataReader.nextSigned(): Int {
    val n = next()
    return (n ushr 1) xor -(n and 1)
}

internal fun readBreakTestCases(data: String): List<BreakTestCase> {
    val reader = ConformanceDataReader(data)
    val result =
        List(reader.testCount) {
            val codePoints = IntArray(reader.number()) { reader.codePoint() }
            BreakTestCase(codePoints, reader.flags(codePoints.size + 1))
        }
    check(reader.isExhausted()) { "Unexpected trailing test data" }
    return result
}

internal fun codePointsToString(codePoints: IntArray): String = buildString {
    for (codePoint in codePoints) {
        if (codePoint < MIN_SUPPLEMENTARY_CODE_POINT) {
            append(codePoint.toChar())
        } else {
            append(Char.MIN_HIGH_SURROGATE + ((codePoint - 0x10000) shr 10))
            append(Char.MIN_LOW_SURROGATE + (codePoint and 0x3FF))
        }
    }
}

private fun IntArray.toHex(): String =
    joinToString(" ") { it.toString(16).uppercase().padStart(4, '0') }
